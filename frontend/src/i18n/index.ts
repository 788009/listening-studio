const messages: Record<SupportedLocale, Record<string, string>> = {
  en: {},
  'zh-CN': zhCN,
}

const activeLocale = ref<SupportedLocale>(browserLocale())

export function matchLocale(value: unknown): SupportedLocale | null {
  if (typeof value !== 'string') return null
  const normalized = value.trim().replace('_', '-').toLocaleLowerCase()
  if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN'
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return null
}

export function browserLocale(): SupportedLocale {
  if (typeof navigator === 'undefined') return 'en'
  for (const value of navigator.languages ?? [navigator.language]) {
    const matched = matchLocale(value)
    if (matched) return matched
  }
  return 'en'
}

export function setLocale(value: unknown): SupportedLocale {
  const locale = matchLocale(value) ?? 'en'
  activeLocale.value = locale
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale
  }
  return locale
}

export function translate(
  key: string,
  parameters: Record<string, string | number> = {},
): string {
  let result = messages[activeLocale.value][key] ?? key
  for (const [name, value] of Object.entries(parameters)) {
    result = result.split(`{${name}}`).join(String(value))
  }
  return result
}

export function translateApiError(code: string, fallback: string): string {
  if (activeLocale.value === 'en') return fallback
  const keys: Record<string, string> = {
    forbidden: 'Operation is not permitted',
    not_found: 'Resource not found',
    profile_incomplete: 'Operation is not permitted',
    conflict: 'Resource state conflicts with this operation',
    user_id_taken: 'This user ID is already in use. Choose another ID.',
    user_id_immutable: 'User ID has already been set and cannot be changed.',
    audio_title_taken: 'An audio with this title already exists.',
    voice_title_taken: 'A voice with this title already exists.',
    validation_error: 'Request validation failed',
    job_failed: 'Task failed',
    internal_error: 'Internal server error',
    unexpected_response: 'The server returned an unexpected response',
  }
  const key = keys[code]
  return key ? translate(key) : fallback
}

export function formatDate(
  value: string | Date,
  options: Intl.DateTimeFormatOptions = {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  },
): string {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return String(value)
  return new Intl.DateTimeFormat(activeLocale.value, options).format(date)
}

export function useI18n() {
  return {
    locale: readonly(activeLocale),
    t: translate,
    formatDate,
  }
}

